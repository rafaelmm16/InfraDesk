export type Role = "admin" | "technician" | "viewer";

export type AssetStatus = "online" | "idle" | "warning" | "offline" | "maintenance";

export type TicketPriority = "critical" | "high" | "medium" | "low";

export type TicketStatus = "open" | "in_progress" | "waiting_user" | "resolved" | "closed";

export type TicketCategory =
  | "hardware"
  | "software"
  | "network"
  | "access_ad"
  | "security"
  | "telemetry_alert";

export type SlaState = "met" | "on_track" | "at_risk" | "breached";

export interface User {
  id: string;
  name: string;
  email: string;
  role: Role;
  department: string;
  createdAt: string;
}

export interface Asset {
  id: string;
  assetTag: string;
  hostname: string;
  domain: string;
  adOu: string;
  ipAddress: string;
  macAddress: string;
  osName: string;
  osVersion: string;
  cpuModel: string;
  ramTotalGb: number;
  diskTotalGb: number;
  loggedUser: string;
  department: string;
  status: AssetStatus;
  cpuPercent: number;
  ramPercent: number;
  diskPercent: number;
  idleMinutes: number;
  uptimeHours: number;
  topProcesses: string[];
  agentVersion: string;
  lastSeenAt: string;
  createdAt: string;
  updatedAt: string;
}

export interface TelemetrySample {
  id: number;
  assetId: string;
  cpuPercent: number;
  ramPercent: number;
  diskPercent: number;
  idleMinutes: number;
  uptimeHours: number;
  loggedUser: string;
  topProcesses: string[];
  recordedAt: string;
}

export interface Ticket {
  id: string;
  code: string;
  title: string;
  description: string;
  category: TicketCategory;
  priority: TicketPriority;
  status: TicketStatus;
  assetId: string | null;
  assetHostname?: string | null;
  requesterName: string;
  requesterDepartment: string;
  assigneeId: string | null;
  assigneeName?: string | null;
  autoGenerated: boolean;
  slaDueAt: string;
  resolvedAt: string | null;
  slaState: SlaState;
  slaRemainingMinutes: number;
  createdAt: string;
  updatedAt: string;
}

export interface TicketComment {
  id: string;
  ticketId: string;
  authorName: string;
  authorRole: Role | "system";
  body: string;
  internal: boolean;
  createdAt: string;
}

export interface AuditLog {
  id: number;
  actorName: string;
  actorEmail: string;
  actorRole: string;
  action: string;
  entityType: "auth" | "asset" | "telemetry" | "ticket" | "ad_sync" | "system";
  entityId: string;
  summary: string;
  ipAddress: string;
  createdAt: string;
}

export interface DashboardSummary {
  fleet: {
    total: number;
    online: number;
    idle: number;
    warning: number;
    offline: number;
    maintenance: number;
    avgCpuPercent: number;
    avgRamPercent: number;
    avgDiskPercent: number;
  };
  tickets: {
    totalActive: number;
    open: number;
    inProgress: number;
    waitingUser: number;
    resolvedToday: number;
    criticalActive: number;
    slaCompliancePercent: number;
    slaBreachedActive: number;
    slaAtRiskActive: number;
  };
  byOu: Array<{
    adOu: string;
    department: string;
    count: number;
    warningCount: number;
    idleCount: number;
  }>;
}

export interface WsEvent {
  type: "telemetry.ingested" | "ticket.created" | "ticket.updated" | "asset.synced";
  timestamp: string;
  payload: unknown;
}
